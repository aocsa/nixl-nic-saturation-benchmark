#!/usr/bin/env python3
"""Write inventory.env from `terraform output -json` (aws/terraform)."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TF = ROOT / "aws" / "terraform"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "inventory.env"


def main() -> None:
    raw = subprocess.check_output(
        ["terraform", "output", "-json"], cwd=TF, text=True
    )
    data = json.loads(raw)
    ips = data["private_ips"]["value"]
    names = data.get("node_names", {}).get("value") or [f"node{i}" for i in range(len(ips))]
    hub = names[0]
    hosts = ",".join(f"{n}:{ip}:{5550 + i}" for i, (n, ip) in enumerate(zip(names, ips)))
    text = f"""# generated by scripts/gen-inventory.py — do not commit
PROFILE=aws-g7e
NIXL_BACKEND=LIBFABRIC
RAIL=efa
CAP_GBS=12.5
CAP_GBPS=100
HUB={hub}
HOSTS={hosts}
NIXL_RV=http://{ips[0]}:8766
NIXL_FILES=http://{ips[0]}:8765
NIXL_RV_BIND=0.0.0.0
NIXL_RV_PORT=8766
FI_PROVIDER=efa
FI_EFA_USE_DEVICE_RDMA=0
FI_EFA_ENABLE_SHM=0
FI_EFA_ENABLE_SHM_TRANSFER=0
RDMAV_FORK_SAFE=1
NIXL_BLOCK_SIZE=16777216
NIXL_BATCH=8
NIXL_ITERS=200
NIXL_WARMUP=50
"""
    OUT.write_text(text)
    print(f"wrote {OUT} hub={hub} n={len(ips)}")


if __name__ == "__main__":
    main()
